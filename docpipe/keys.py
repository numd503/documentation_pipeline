"""Нормализация ключей: одно правило на весь проект.

Ключ узла данных, ключ шва и ключ точки входа приводятся к канонической форме
**здесь и больше нигде**. Причина та же, по которой `route.py` лежит не под
`web/`: вторая нормализация разойдётся с первой на первом же частном случае
и разойдётся молча — записи просто перестанут находить друг друга, а отчёт
покажет «таблица объявлена, обращений нет» плюс «обращение к неизвестной
таблице», то есть две находки вместо одной связи.

Правило записано в плане графа дважды (R03 п. 7 и G02 п. 5) именно потому,
что нарушить его легко: нормализация выглядит мелочью, которую проще написать
на месте, чем импортировать.

Что здесь **не** делается: ни морфологии, ни синонимов, ни стеммера. Смысл
приносит вызывающий (Р12), а нормализация отвечает только за «одна и та же
вещь, записанная по-разному, даёт один ключ».
"""

import re

from docpipe.route import normalize_route

# Кириллическая «ё» приводится к «е» на нашей стороне — при индексации
# и при разборе запроса одним правилом. Причина в G10: `LOWER()` и `NOCASE`
# в SQLite без ICU сворачивают только ASCII, и русский поиск умер бы молча,
# а тесты на английских именах этого бы не показали.
_YO = str.maketrans({"ё": "е", "Ё": "Е"})

_WHITESPACE = re.compile(r"\s+")
# Кавычки и скобки, которыми обрамляют имена в SQL: [dbo].[FOO], "public"."foo",
# `db`.`foo`. Все три диалекта встречаются в одном репозитории.
_QUOTES = re.compile(r"[\[\]\"`]")


def normalize_text(value: str) -> str:
    """Свободный текст к сравнимой форме: регистр, «ё», пробелы.

    `casefold`, а не `lower`: он единственный правильно сворачивает регистр
    вне ASCII, а весь предметный словарь целевого репозитория — русские
    `DisplayName` (G05b).
    """
    return _WHITESPACE.sub(" ", value.translate(_YO).strip()).casefold()


def normalize_identifier(value: str) -> str:
    """Идентификатор-якорь: имя грид-сервиса, имя очереди, имя workflow.

    Регистр сворачивается, потому что стороны пишут якорь по-разному
    (`CalcDxExcel` в реестре и `calcdxexcel` в конфигурации), а пробелы внутри
    идентификатора не значат ничего.
    """
    return normalize_text(value)


def normalize_data_name(value: str) -> str:
    """Имя таблицы, представления или процедуры: `[dbo].[USER_TASKS]` → `dbo.user_tasks`.

    Схема **не дописывается**: `USER_TASKS` и `dbo.USER_TASKS` остаются разными
    ключами. Дописать умолчание `dbo` заманчиво и неверно — на репозитории
    с несколькими схемами это склеит таблицы разных схем в одну, и узел
    данных станет уверенно неправильным (Р6), а не отсутствующим.
    """
    cleaned = _QUOTES.sub("", value).strip()
    parts = [part.strip() for part in cleaned.split(".")]
    return ".".join(normalize_text(part) for part in parts if part)


def normalize_seam_literal(seam_kind: str, value: str) -> str:
    """Ключ шва. HTTP-маршрут нормализуется маршрутной нормализацией, остальное —
    как идентификатор.

    Разные правила здесь не роскошь: у маршрута есть подстановки (`{id}`, `:id`,
    `${id}`), схема, хост и query, и всё это обязано схлопнуться в одну форму,
    иначе фронт и бэк не сойдутся. У имени очереди ничего этого нет, и прогон
    его через маршрутную нормализацию отрезал бы всё после `?`.
    """
    if seam_kind == "http_route":
        return normalize_route(value)
    return normalize_identifier(value)


def normalize_route_reference(http_method: str, route: str) -> str:
    """Ключ HTTP-точки входа: метод и маршрут в одной строке.

    Метод входит в ключ, потому что `GET api/items` и `POST api/items` —
    разные точки входа. Пустой метод законен: сторона, которая глагола
    не знает, пишет только маршрут.
    """
    method = http_method.strip().upper()
    normalized = normalize_route(route)
    return f"{method} {normalized}".strip()
