"""Модели нашего индекса графа.

Наш индекс — единственное, что читают остальные фичи. Граф движка живёт
за мостом, и его словарь сюда не попадает: у ребра здесь наш вид, а `via`
называет способ получения — включая вид ребра движка и версию его индекса,
когда ребро пришло оттуда.

Схема версионирована. Несовпадение версии — отказ с командой пересборки,
а не смешанное чтение: индекс, собранный другой версией кода, отвечает
на вопросы по-другому, и понять это по ответу нельзя.
"""

from typing import Final

from pydantic import BaseModel, ConfigDict, Field

SCHEMA_VERSION: Final[str] = "1"

# Виды узлов. Перечень положительный: узел нового вида обязан попасть сюда
# осознанно. `entry_point`, `data` и `seam` придут из R03 и фич G03–G06.
NODE_KINDS: Final[tuple[str, ...]] = ("module", "type", "member", "entry_point", "data", "seam")

# Виды рёбер и то, кто их источник, — таблица из плана. `calls` бывает
# и от движка, и от нашего довершения; различает их `via`, а не вид.
EDGE_KINDS: Final[tuple[str, ...]] = (
    "calls",
    "implements",
    "inherits",
    "binds",
    "dispatches",
    "reads",
    "writes",
    "touches",
    "references",
    "crosses",
    # `owns` — «тип содержит член». В индексе его нет: он появляется только
    # в ответе о пути, где иначе пришлось бы называть вызовом связь,
    # которая исполнением не является.
    "owns",
)


class _Base(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class GraphNode(_Base):
    """Узел нашего индекса.

    `key` — наш ключ и только наш. Идентификатор узла движка ключом быть
    не может: он не документирован, не обещан стабильным между версиями
    и умрёт вместе с движком при переключении на запасной вариант.
    """

    key: str = Field(min_length=1)
    kind: str
    name: str = ""
    # Имя типа-владельца у члена. Отдельным полем, а не разбором ключа:
    # разбор строки — это вторая реализация правила сборки ключа.
    owner: str = ""
    file: str = ""
    lang: str = ""
    # Откуда узел: `engine`, `manifest`, `registry`. Провенанс нужен не для
    # отчётности: первая же ошибка источника иначе становится неотличима
    # от факта.
    source: str = "engine"
    attributes: dict[str, str] = Field(default_factory=dict)


class GraphEdge(_Base):
    """Ребро нашего индекса.

    Каждое ребро обязано нести способ получения (`via`) и уверенность.
    У рёбер, взятых у движка, `via` называет вид ребра движка и версию
    его индекса — без этого нельзя ответить, чьё ребро соврало.
    """

    kind: str
    source: str = Field(min_length=1)
    target: str = Field(min_length=1)
    via: str = Field(min_length=1)
    confidence: float = 1.0
    attributes: dict[str, str] = Field(default_factory=dict)


class GraphMeta(_Base):
    """Паспорт индекса: чем собран, из чего и что при этом потерялось."""

    schema_version: str = SCHEMA_VERSION
    # Поколение выводится из содержимого, а не из времени: два прогона
    # на одном входе обязаны дать одно поколение, иначе читатель не отличит
    # «индекс пересобрали» от «индекс тот же». Времени в индексе нет вовсе.
    generation: str
    engine_version: str = ""
    engine_checksum: str = ""
    repo: str = ""
    counts: dict[str, int] = Field(default_factory=dict)
    # Категории неполноты: что отсеяно и почему. Молча выброшенное через
    # месяц неотличимо от потерянного (Р8).
    report: dict[str, int] = Field(default_factory=dict)
    # Порядок корней: биты масок достижимости назначены именно ему.
    # Без него маска — набор чисел без смысла.
    roots: tuple[str, ...] = ()


class GraphIndex(_Base):
    """Логическое содержимое индекса — то, по чему считается хэш (Р4).

    Хэш берётся по узлам **с атрибутами** и рёбрам, отсортированным по нашим
    ключам. Хэш только по рёбрам молча пропустил бы сменившийся провенанс,
    уверенность или имя узла.
    """

    nodes: tuple[GraphNode, ...] = ()
    edges: tuple[GraphEdge, ...] = ()
